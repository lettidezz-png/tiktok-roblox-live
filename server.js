const express = require("express")

const app = express()

/////////////////////////////////////////////////
// STORAGE
/////////////////////////////////////////////////

let queue = []

/////////////////////////////////////////////////
// ROOT
/////////////////////////////////////////////////

app.get("/", (req, res) => {

    res.send("SERVER WORKING")

})

/////////////////////////////////////////////////
// USERNAME WEBHOOK
/////////////////////////////////////////////////

app.get("/username", (req, res) => {

    const username =
        req.query.username

    console.log(
        "NEW USER:",
        username
    )

    if (
        username &&
        username !== "undefined"
    ) {

        queue.push(username)
    }

    res.send("ok")

})

/////////////////////////////////////////////////
// QUEUE
/////////////////////////////////////////////////

app.get("/queue", (req, res) => {

    res.json(queue)

    queue = []

})

/////////////////////////////////////////////////
// SERVER
/////////////////////////////////////////////////

const PORT =
process.env.PORT || 3000

app.listen(PORT, () => {

    console.log(
        "SERVER STARTED"
    )

})